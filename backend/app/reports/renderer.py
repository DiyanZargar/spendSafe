import io
from typing import Dict, Any
from decimal import Decimal
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.patches as patches


def render_financial_report(data: Dict[str, Any]) -> bytes:
    """
    Renders a modern, visually stunning PNG financial infographic card
    suitable for downloading in the web dashboard or sending via WhatsApp / Telegram.
    """
    period_title = data.get("period", "Monthly Report")
    summary = data.get("summary", {})
    categories = data.get("categories", [])
    trends = data.get("trends", [])
    currency = data.get("currency", "USD")

    total_amount = float(summary.get("total_amount", 0.0))
    daily_avg = float(summary.get("average_daily", 0.0))
    tx_count = summary.get("transaction_count", 0)

    # Setup Figure with dark aesthetic
    fig = plt.figure(figsize=(12, 8), facecolor="#0f172a")
    plt.style.use("dark_background")

    # Header Title
    fig.text(0.08, 0.93, f"Financial Report: {period_title.upper()}",
             fontsize=20, fontweight="bold", color="#ffffff")
    fig.text(0.08, 0.89, "Agentic Expense Tracker  •  Automated Analysis",
             fontsize=11, color="#94a3b8")

    # 3 Metric Cards (Backgrounds and text)
    metric_cards = [
        ("TOTAL SPENDING", f"{currency} {total_amount:,.2f}", "#38bdf8"),
        ("DAILY AVERAGE", f"{currency} {daily_avg:,.2f}", "#34d399"),
        ("TOTAL TRANSACTIONS", f"{tx_count:,}", "#a78bfa"),
    ]

    card_width = 0.26
    for i, (label, val, accent_color) in enumerate(metric_cards):
        x = 0.08 + i * 0.30
        rect = patches.FancyBboxPatch(
            (x, 0.76), card_width, 0.10,
            boxstyle="round,pad=0.015,rounding_size=0.02",
            facecolor="#1e293b", edgecolor=accent_color, linewidth=1.5,
            transform=fig.transFigure, clip_on=False
        )
        fig.patches.append(rect)
        fig.text(x + 0.015, 0.825, label, fontsize=9, fontweight="bold", color="#94a3b8")
        fig.text(x + 0.015, 0.78, val, fontsize=15, fontweight="bold", color="#f8fafc")

    # Left Subplot: Category Breakdown (Barh)
    ax1 = fig.add_axes([0.08, 0.12, 0.38, 0.56], facecolor="#1e293b")
    if categories:
        top_cats = categories[:7]
        cat_names = [c["category"] for c in top_cats][::-1]
        cat_amounts = [float(c["amount"]) for c in top_cats][::-1]
        colors = ["#38bdf8", "#34d399", "#a78bfa", "#f472b6", "#fb923c", "#facc15", "#94a3b8"][:len(cat_names)][::-1]

        bars = ax1.barh(cat_names, cat_amounts, color=colors, height=0.55, edgecolor="none")
        ax1.set_title("Top Spending Categories", fontsize=12, fontweight="bold", color="#ffffff", pad=12)
        ax1.grid(axis="x", linestyle="--", alpha=0.15, color="#ffffff")
        ax1.tick_params(colors="#94a3b8", labelsize=10)
        for spine in ax1.spines.values():
            spine.set_visible(False)

        for bar in bars:
            width = bar.get_width()
            ax1.text(width + (total_amount * 0.02), bar.get_y() + bar.get_height()/2,
                     f"{currency} {width:,.0f}",
                     va="center", ha="left", color="#e2e8f0", fontsize=9, fontweight="bold")
    else:
        ax1.text(0.5, 0.5, "No Category Data Available", ha="center", va="center", color="#64748b", fontsize=12)
        ax1.axis("off")

    # Right Subplot: Daily Spending Trend (Area/Line)
    ax2 = fig.add_axes([0.54, 0.12, 0.38, 0.56], facecolor="#1e293b")
    if trends:
        trend_dates = [t["date"][-5:] for t in trends]  # MM-DD
        trend_values = [float(t["amount"]) for t in trends]

        ax2.plot(trend_dates, trend_values, color="#38bdf8", linewidth=2.5, marker="o", markersize=4)
        ax2.fill_between(trend_dates, trend_values, color="#38bdf8", alpha=0.15)
        ax2.set_title("Spending Trend Over Time", fontsize=12, fontweight="bold", color="#ffffff", pad=12)
        ax2.grid(True, linestyle="--", alpha=0.15, color="#ffffff")
        ax2.tick_params(colors="#94a3b8", labelsize=9)
        for spine in ax2.spines.values():
            spine.set_visible(False)

        # Rotate x labels if many
        if len(trend_dates) > 10:
            step = max(1, len(trend_dates) // 8)
            ax2.set_xticks(range(0, len(trend_dates), step))
            ax2.set_xticklabels([trend_dates[i] for i in range(0, len(trend_dates), step)], rotation=30)
    else:
        ax2.text(0.5, 0.5, "No Trend Data Available", ha="center", va="center", color="#64748b", fontsize=12)
        ax2.axis("off")

    # Footer note
    fig.text(0.5, 0.04, "Generated by Agentic Expense Platform • Confidential Financial Summary",
             ha="center", fontsize=9, color="#64748b")

    buf = io.BytesIO()
    plt.savefig(buf, format="png", dpi=150, bbox_inches="tight", facecolor=fig.get_facecolor(), edgecolor="none")
    plt.close(fig)
    return buf.getvalue()
